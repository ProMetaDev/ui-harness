#!/usr/bin/env bash
# 生成 12 个合成多文件仓库，只用于自测 bench_repos.py 的索引/报告/跳过逻辑。
#
# 重要：这些**不是真实仓库**，不参与任何真实评测数字，也不能编译/测试。
# 每个仓库约 1500 行、8 个文件，根目录有 SYNTHETIC_FIXTURE.md 明确标注。
#
# 用法：
#   bash tools/make_bench_fixtures.sh [输出目录]
# 默认输出到 bench/out/fixtures（bench/out 被 .gitignore 忽略）。
set -uo pipefail

OUT=${1:-bench/out/fixtures}
case "$OUT" in
  -h|--help)
    sed -n '1,12p' "${BASH_SOURCE[0]}"
    exit 0
    ;;
esac

# 每个 spec：目录名|扩展名|符号前缀|注释前缀|语言
SPECS=(
  "synth-rust|rs|pub fn|//|rust"
  "synth-python|py|def|#|python"
  "synth-go|go|function|//|go"
  "synth-javascript|js|function|//|javascript"
  "synth-c|c|const int|//|c"
  "synth-java|java|class|//|java"
  "synth-ruby|rb|def|#|ruby"
  "synth-php|php|function|//|php"
  "synth-csharp|cs|class|//|csharp"
  "synth-kotlin|kt|class|//|kotlin"
  "synth-swift|swift|class|//|swift"
  "synth-lua|lua|function|--|lua"
)

rm -rf "$OUT"
mkdir -p "$OUT"

gen_source() {
  local file=$1 ext=$2 sym=$3 comment=$4
  awk -v sym="$sym" -v comment="$comment" -v ext="$ext" '
    BEGIN {
      if (ext == "py") {
        print "# 合成 fixture，不是真实仓库。"
        print "# generated by tools/make_bench_fixtures.sh"
      } else {
        print "/*"
        print " * 合成 fixture，不是真实仓库。"
        print " * generated by tools/make_bench_fixtures.sh"
        print " */"
      }
      for (i = 1; i <= 220; i++) {
        if (i % 20 == 1) {
          name = "fixture_" i
          if (ext == "py") {
            print "def " name "():"
          } else if (sym == "const int") {
            print "const int " name " = " i ";"
          } else if (sym == "class") {
            print "class " name " {"
          } else if (sym == "pub fn") {
            print "pub fn " name "() {"
          } else {
            print sym " " name "() {"
          }
        } else if (ext == "py") {
          print "    pass  # synthetic line " i
        } else if (sym == "const int") {
          print comment " synthetic line " i
        } else {
          print "  " comment " synthetic line " i
        }
      }
      if (ext != "py" && sym == "class") print "}"
      if (ext != "py" && sym != "class" && sym != "const int") print "}"
    }
  ' > "$file"
}

count=0
for spec in "${SPECS[@]}"; do
  IFS='|' read -r name ext sym comment language <<< "$spec"
  root="$OUT/$name"
  mkdir -p "$root/src" "$root/tests"
  {
    echo "# 合成 fixture，不是真实仓库"
    echo
    echo "本目录由 \`tools/make_bench_fixtures.sh\` 生成，语言标记为 \`$language\`，"
    echo "包含约 1500 行、8 个文件，**不能编译、不能运行、不参与真实评测**。"
    echo "真实仓库评测的选仓与记录方式见 docs/56-real-repos.md。"
  } > "$root/SYNTHETIC_FIXTURE.md"
  {
    echo "# $name"
    echo
    echo "合成 fixture（不是真实仓库）。"
  } > "$root/README.md"

  for f in 1 2 3 4 5 6; do
    gen_source "$root/src/module_$f.$ext" "$ext" "$sym" "$comment"
  done
  for f in 1 2 3; do
    gen_source "$root/tests/test_$f.$ext" "$ext" "$sym" "$comment"
  done
  count=$((count + 1))
done

echo "生成 $count 个合成 fixture 到 $OUT（每个约 1500 行；不是真实仓库）"
